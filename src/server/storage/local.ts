import { createReadStream } from "node:fs";
import { mkdir, open, rename, rm, stat } from "node:fs/promises";
import path from "node:path";
import { Readable } from "node:stream";
import { StorageError, type UploadTarget, type VideoStorage } from "./types";

const KEY_PATTERN = /^videos\/[0-9a-f-]{36}\.(mp4|webm|mov)$/;

export class UploadTooLargeError extends Error {}

/**
 * Stores videos on the server's disk. Suitable for development and single-server
 * deployments with a persistent volume — not for serverless platforms, whose
 * filesystems are ephemeral and whose request bodies are size-capped.
 */
export class LocalVideoStorage implements VideoStorage {
  readonly driver = "local" as const;

  constructor(private readonly root: string) {}

  /** Keys are generated by the server; the check is defense in depth against path traversal. */
  pathFor(key: string): string {
    if (!KEY_PATTERN.test(key)) throw new StorageError("Invalid storage key.");
    return path.join(this.root, path.basename(key));
  }

  async createUploadTarget(_key: string, contentType: string, localUploadUrl: string): Promise<UploadTarget> {
    return { url: localUploadUrl, method: "PUT", headers: { "Content-Type": contentType } };
  }

  /**
   * Streams a request body to disk without buffering it in memory, aborting as soon as
   * it exceeds `expectedBytes`. The file only appears under its final name when complete.
   */
  async write(key: string, body: ReadableStream<Uint8Array>, expectedBytes: number): Promise<{ bytes: number; head: Uint8Array }> {
    const finalPath = this.pathFor(key);
    const tempPath = `${finalPath}.part`;
    await mkdir(this.root, { recursive: true });
    const file = await open(tempPath, "w");
    const reader = body.getReader();
    let bytes = 0;
    let head = new Uint8Array(0);
    try {
      for (;;) {
        const { done, value } = await reader.read();
        if (done) break;
        bytes += value.byteLength;
        if (bytes > expectedBytes) {
          await reader.cancel();
          throw new UploadTooLargeError("The upload is larger than declared.");
        }
        if (head.length < 64) {
          const merged = new Uint8Array(Math.min(64, head.length + value.byteLength));
          merged.set(head);
          merged.set(value.subarray(0, merged.length - head.length), head.length);
          head = merged;
        }
        await file.write(value);
      }
      await file.close();
      await rename(tempPath, finalPath);
      return { bytes, head };
    } catch (error) {
      await file.close().catch(() => undefined);
      await rm(tempPath, { force: true });
      throw error;
    }
  }

  async size(key: string): Promise<number | null> {
    try {
      return (await stat(this.pathFor(key))).size;
    } catch {
      return null;
    }
  }

  async readHead(key: string, length: number): Promise<Uint8Array> {
    const file = await open(this.pathFor(key), "r");
    try {
      const buffer = new Uint8Array(length);
      const { bytesRead } = await file.read(buffer, 0, length, 0);
      return buffer.subarray(0, bytesRead);
    } finally {
      await file.close();
    }
  }

  async delete(key: string): Promise<void> {
    await rm(this.pathFor(key), { force: true });
    await rm(`${this.pathFor(key)}.part`, { force: true });
  }

  /** Web stream for a byte range (inclusive end), used by the media route. */
  stream(key: string, start: number, end: number): ReadableStream<Uint8Array> {
    return Readable.toWeb(createReadStream(this.pathFor(key), { start, end })) as ReadableStream<Uint8Array>;
  }
}
